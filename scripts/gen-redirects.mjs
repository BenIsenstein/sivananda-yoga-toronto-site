/**
 * Generates public/_redirects (Netlify/Cloudflare-style host-level 301s) from
 * the single source of truth in src/config/redirects.mjs. Run: `node scripts/gen-redirects.mjs`.
 * Kept in the repo so the static host can serve true 301s (Astro's built-in
 * redirects emit meta-refresh HTML pages, not real 301 status codes).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { redirectMap } from '../src/config/redirects.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const out = resolve(__dirname, '../public/_redirects');

const lines = [
  '# Generated by scripts/gen-redirects.mjs — do not edit by hand.',
  '# Legacy WordPress paths → new routes (301).',
  '',
];

for (const [from, to] of Object.entries(redirectMap)) {
  lines.push(`${from} ${to} 301`);
}
lines.push('');

writeFileSync(out, lines.join('\n'));
process.stdout.write(`Wrote ${Object.keys(redirectMap).length} redirects → public/_redirects\n`);
